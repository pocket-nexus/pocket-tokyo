/// Side of a glyph's square in the atlas, and glyphs in a row of it.
pub const CELL: usize = 8;
pub const ACROSS: usize = 32;
/// The atlas: `ACROSS × CELL` by `2 × CELL` texels.
pub const ATLAS_W: usize = ACROSS * CELL;
pub const ATLAS_H: usize = 2 * CELL;
/// Texels from one letter to the next.
pub const ADVANCE: usize = 6;

/// Where a character's glyph is in the atlas (texels). Small letters are drawn as capitals; a character
/// without a glyph as a space.
pub fn glyph(c: u8) -> (usize, usize) {
    let c = c.to_ascii_uppercase();
    let i = GLYPHS.iter().position(|g| g.0 == c).unwrap_or(0);
    ((i % ACROSS) * CELL, (i / ACROSS) * CELL)
}

/// Draws the atlas: `out` holds `ATLAS_W × ATLAS_H` texels in rows, 1 where a dot is.
pub fn atlas(out: &mut [u8]) {
    for (i, (_, rows)) in GLYPHS.iter().enumerate() {
        let (x0, y0) = ((i % ACROSS) * CELL, (i / ACROSS) * CELL);
        for (y, row) in rows.iter().enumerate() {
            for x in 0..5 {
                out[(y0 + y) * ATLAS_W + x0 + x] = (row >> (4 - x)) & 1;
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_glyph_has_a_square_of_its_own() {
        let mut texels = [0u8; ATLAS_W * ATLAS_H];
        atlas(&mut texels);
        assert_eq!(glyph(b'a'), glyph(b'A'));
        assert_eq!(glyph(b'~'), glyph(b' '));
        let (x, y) = glyph(b'T');
        assert_eq!(&texels[y * ATLAS_W + x..y * ATLAS_W + x + 5], &[1, 1, 1, 1, 1]);
        assert!(GLYPHS.len() <= 2 * ACROSS);
    }
}
